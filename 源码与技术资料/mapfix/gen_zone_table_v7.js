/* gen_zone_table_v7.js - regenerate zone_table.h for mapfix from the CORRECTED 成品包v7 gxt (V7c: Liberty state label now 自由城 per user 2026-09-19)
   (authoritative current zone translations), replacing gen_zone_table.js's stale M7明细 source.
   Reads the 74 info.zon zone-key hashes, looks up each key's CURRENT zh in v7 本体 gxt,
   verifies every char is in the M4e char_table, emits ASCII-only zone_table.h + ref tsv. */
const fs = require('fs');
const { parseGxt } = require('../gxt_io.js');
const ENG = 'E:/SteamLibrary/steamapps/common/Grand Theft Auto IV/汉化补丁工程';
const ALIGN = ENG + '/02-英中对齐表/';
const V7 = ENG + '/03-补丁构建/成品包v7/';

const ct = fs.readFileSync(ENG + '/03-补丁构建/M4f字库包/plugins/GTA4.CHS/char_table.dat');
const ctn = ct.readUInt32LE(0); const cpSet = new Set(); for (let i = 0; i < ctn; i++) cpSet.add(ct.readUInt32LE(4 + i * 4));
console.log('char_table codepoints:', ctn);

// zone keys: zon键 -> GXT哈希
const zt = fs.readFileSync(ALIGN + '区名-info_zon-74键.tsv', 'utf8').replace(/^\uFEFF/, '').split(/\r?\n/);
const hi = zt[0].split('\t').indexOf('GXT哈希');
const zoneHashes = [];
for (const line of zt.slice(1)) { const c = line.split('\t'); if (c.length > hi && c[hi]) zoneHashes.push((parseInt(c[hi], 16) >>> 0)); }
console.log('zone keys:', zoneHashes.length);

// v7 本体 gxt current values by hash
const g = parseGxt(V7 + 'update/common/text/american.gxt');
const main = g.recs.find(r => r.name.replace(/\0.*$/, '') === 'MAIN');
const byHash = new Map(main.items.map(it => [it.hash >>> 0, it.s]));

const names = [];
let missing = [];
for (const h of zoneHashes) {
  const nm = byHash.get(h);
  if (!nm) { console.error('!! zone hash ' + h.toString(16) + ' not found in v7 gxt'); process.exit(1); }
  names.push(nm);
}
// EXTRA: pause-map state indicator also goes through the -0x20 corrupted path; Liberty (state)
// is not among the 74 info.zon keys, so add it here or it renders garbled on the pause map.
{
  const st = byHash.get(0x165feb52);
  if (st) names.push(st);
}
for (const nm of names) {
  for (const cp of [...nm].map(ch => ch.codePointAt(0))) if (!cpSet.has(cp)) missing.push(nm + ' U+' + cp.toString(16));
}
console.log('zone names pulled from v7 gxt:', names.length);
if (missing.length) { console.error('!! MISSING FROM char_table:'); missing.forEach(m => console.error('   ' + m)); process.exit(1); }
console.log('OK: all zone names covered by char_table');

const MAXLEN = 16;
let h = '/* zone_table.h - AUTO-GENERATED by gen_zone_table_v7.js from 成品包v7 gxt. ASCII-only. Do not edit by hand. */\n';
h += '#pragma once\n#define ZONE_COUNT ' + names.length + '\n#define ZONE_MAXLEN ' + MAXLEN + '\n';
h += 'static const unsigned short ZONE_REAL[ZONE_COUNT][ZONE_MAXLEN] = {\n';
const lens = [];
names.forEach((nm, idx) => {
  const cps = [...nm].map(ch => '0x' + ch.codePointAt(0).toString(16).padStart(4, '0'));
  lens.push(cps.length); while (cps.length < MAXLEN) cps.push('0x0000');
  h += '  {' + cps.join(',') + '}' + (idx < names.length - 1 ? ',' : '') + '  /* idx ' + idx + ' len ' + lens[idx] + ' */\n';
});
h += '};\nstatic const unsigned char ZONE_LEN[ZONE_COUNT] = {' + lens.join(',') + '};\n';
fs.writeFileSync(ENG + '/01-逆向草稿/procdiag/zone_table.h', h, 'latin1');
console.log('wrote zone_table.h (' + h.length + ' bytes)');
let ref = 'idx\tlen\treal\tminus20_form\n';
names.forEach((nm, i) => { const bad = [...nm].map(c => String.fromCharCode((c.codePointAt(0) - 0x20) & 0xffff)).join(''); ref += i + '\t' + lens[i] + '\t' + nm + '\t' + bad + '\n'; });
fs.writeFileSync(ENG + '/01-逆向草稿/procdiag/zone_table_ref.tsv', '\uFEFF' + ref, 'utf8');
console.log('wrote zone_table_ref.tsv');
// show the corrected zone names that differ from old (spot check)
for (const kw of ['阿尔冈琴', '波汉', '北伍德', '追逐角', '左伍德', '比奇伍德城']) {
  const hits = names.filter(n => n.includes(kw)); if (hits.length) console.log('  ' + kw + ': ' + hits.join(' / '));
}
